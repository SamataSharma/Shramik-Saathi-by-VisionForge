let currentLang = 'en';

// Initialize from localStorage immediately
try {
  const saved = localStorage.getItem('mine_ar_lang');
  if (saved && translations[saved]) {
    currentLang = saved;
  }
} catch (e) {
  console.warn('[i18n] Error reading saved language:', e);
}

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    try {
      localStorage.setItem('mine_ar_lang', lang);
    } catch (e) {}

    // Update document lang attribute
    document.documentElement.lang = lang;

    // Dispatch app-wide event
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
}

export function t(key, fallbackText) {
  const dict = translations[currentLang] || translations.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  // Fallback to English
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  // If fallbackText provided, use it
  if (fallbackText) {
    return fallbackText;
  }
  return key;
}
